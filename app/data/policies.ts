// closing: 모달 하단 옐로 "김덕홍의 약속" 블록 문구

export type PolicyTheme = "future" | "life" | "warm";

/** 단일 줄(문자열) 또는 메인+세부(객체) */
export type PolicyBullet = string | { head: string; sub: string[] };

export type Policy = {
  /** 정책 번호 (1~6) */
  n: number;
  theme: PolicyTheme;
  /** 카드/모달 제목 */
  title: string;
  /** 한 줄 요약 (카드 + 모달 헤더) */
  summary: string;
  /** 추진 과제 */
  bullets: PolicyBullet[];
  /** 약속 문구 (모달 하단 옐로 블록) */
  closing: string;
};

